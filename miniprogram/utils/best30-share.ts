// best30-share.ts
// Best30 分享图生成：skyblue 纯色背景 + 首行身份卡（头像/铭牌 + 两个 logo）+ 6x5 透明边框网格填满前 30。
// 依赖 type="2d" 的离屏 canvas；导出临时文件后走 wx.shareFileMessage（微信分享面板），
// 不支持时退回保存相册。
import type { BestScoreView, ProfileHeaderView } from './api'

/** 分享图逻辑尺寸（px）；实际像素 = 逻辑 x dpr */
export const BEST30_SHARE_SIZE = {
  width: 1080,
  height: 1502,
}

const MARGIN = 40
const AVATAR_SIZE = 112
const PLATE_W = 396
const PLATE_H = 134
const LOGO_BOX = 128
const LOGO_GAP = 16
/** maiLogo 独立放大盒宽（高 = 头像高，fit 保持比例，不挤压不变形） */
const MAILOGO_BOX_W = 220
const GAP = 14
const COLS = 5
const ROWS = 6
const CELL_W = 188
const CELL_H = 196
const TABLE_X = 42
const TABLE_Y = 200

/** 难度色调（与 plays 一致），用于 canvas 上描难度标签与定数文字 */
const TONE_COLORS: Record<string, string> = {
  easy: '#45aeff',
  basic: '#6fd43d',
  advanced: '#f8b807',
  expert: '#f82f43',
  master: '#9f51dc',
  remaster: '#d172ed',
  other: '#8c8c8c',
}

/** Rating 分段底色（对应 app.wxss 的 .rating-*，铜/银/金/彩虹用近似纯色） */
const RATING_COLORS: Record<string, string> = {
  white: '#ffffff',
  blue: '#45aeff',
  green: '#6fd43d',
  yellow: '#f8b807',
  red: '#f82f43',
  purple: '#9f51dc',
  copper: '#c97a33',
  silver: '#b8bdc4',
  gold: '#d9a92b',
  rainbow: '#b23fd0',
}

const SKYBLUE = '#87ceeb'
const TEXT_DARK = '#1f1f1f'
const TEXT_GRAY = '#555555'
const TEXT_BLUE = '#d1542b'
const PLATE_BG = '#eef2f8'
const PLATE_BORDER = '#cdd6e2'
const OUTLINE = '#000000'

/** 页脚署名文案 */
const FOOTER_TEXT = 'Desgin by Azerole | Generated by maitea mini-app'
/** 页脚基线 y（图片底部） */
const FOOTER_Y = BEST30_SHARE_SIZE.height - 16

const loadImage = (canvas: any, src: string, timeoutMs = 6000): Promise<any> => {
  return new Promise((resolve, reject) => {
    let done = false
    const timer = setTimeout(() => {
      if (!done) {
        done = true
        reject(new Error('image timeout'))
      }
    }, timeoutMs)
    let img: any
    try {
      img = canvas.createImage()
    } catch (e) {
      reject(e)
      return
    }
    img.onload = () => {
      if (!done) {
        done = true
        clearTimeout(timer)
        resolve(img)
      }
    }
    img.onerror = () => {
      if (!done) {
        done = true
        clearTimeout(timer)
        reject(new Error('image error'))
      }
    }
    img.src = src
  })
}

const drawRoundRect = (
  ctx: any,
  x: number,
  y: number,
  w: number,
  h: number,
  r: number
): void => {
  ctx.beginPath()
  ctx.moveTo(x + r, y)
  ctx.lineTo(x + w - r, y)
  ctx.arcTo(x + w, y, x + w, y + r, r)
  ctx.lineTo(x + w, y + h - r)
  ctx.arcTo(x + w, y + h, x + w - r, y + h, r)
  ctx.lineTo(x + r, y + h)
  ctx.arcTo(x, y + h, x, y + h - r, r)
  ctx.lineTo(x, y + r)
  ctx.arcTo(x, y, x + r, y, r)
  ctx.closePath()
}

const truncateText = (
  ctx: any,
  text: string,
  maxWidth: number,
  font?: string
): string => {
  if (!text) {
    return ''
  }
  if (font) {
    ctx.font = font
  }
  if (ctx.measureText(text).width <= maxWidth) {
    return text
  }
  let out = text
  while (out.length > 1 && ctx.measureText(out + '…').width > maxWidth) {
    out = out.slice(0, -1)
  }
  return out + '…'
}
/**
 * 按比例把图片放进 boxW x boxH 的盒子（默认 fit 居中；cover 填满裁切），
 * 可选圆角裁切。加载失败返回 false（调用方可回退绘制）。
 */
const drawImageBox = async (
  ctx: any,
  canvas: any,
  src: string,
  x: number,
  y: number,
  boxW: number,
  boxH: number,
  opts: { radius?: number; cover?: boolean } = {}
): Promise<boolean> => {
  if (!src) {
    return false
  }
  try {
    const img = await loadImage(canvas, src)
    const iw = img.width || 1
    const ih = img.height || 1
    const scale = opts.cover
      ? Math.max(boxW / iw, boxH / ih)
      : Math.min(boxW / iw, boxH / ih)
    const dw = iw * scale
    const dh = ih * scale
    const dx = x + (boxW - dw) / 2
    const dy = y + (boxH - dh) / 2
    if (opts.radius) {
      drawRoundRect(ctx, x, y, boxW, boxH, opts.radius)
      ctx.save()
      ctx.clip()
      ctx.drawImage(img, dx, dy, dw, dh)
      ctx.restore()
    } else {
      ctx.drawImage(img, dx, dy, dw, dh)
    }
    return true
  } catch (e) {
    return false
  }
}

/** 白字黑描边（模拟页面 text-shadow：先 stroke 黑色描边，再 fill 本体色） */
const fillTextOutline = (
  ctx: any,
  text: string,
  x: number,
  y: number,
  font: string,
  color: string,
  strokeWidth = 4
): void => {
  ctx.font = font
  ctx.lineJoin = 'round'
  ctx.miterLimit = 2
  ctx.strokeStyle = OUTLINE
  ctx.lineWidth = strokeWidth
  ctx.strokeText(text, x, y)
  ctx.fillStyle = color
  ctx.fillText(text, x, y)
}

/** 取能放进 maxW 的最大字号（basePx 往下逐 1px 找，不低于 minPx），并设置 ctx.font */
const fitFontPx = (
  ctx: any,
  text: string,
  maxW: number,
  basePx: number,
  minPx = 11,
  weight = 'bold'
): string => {
  let px = basePx
  while (px > minPx) {
    ctx.font = `${weight} ${px}px sans-serif`
    if (ctx.measureText(text).width <= maxW) {
      break
    }
    px -= 1
  }
  ctx.font = `${weight} ${px}px sans-serif`
  return ctx.font
}

/** 第一行：头像 + 铭牌（左），maitea_logo.png + maiLogo.png（右） */
const drawHeader = async (
  ctx: any,
  canvas: any,
  profile: ProfileHeaderView | null
): Promise<void> => {
  // 右上角：生成日期（YYYY-MM-DD，本地时区）
  const now = new Date()
  const dateStr = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(
    now.getDate()
  ).padStart(2, '0')}`
  ctx.font = '24px sans-serif'
  ctx.fillStyle = TEXT_GRAY
  ctx.textAlign = 'right'
  ctx.fillText(dateStr, BEST30_SHARE_SIZE.width - MARGIN, 28)
  ctx.textAlign = 'left'

  // 头像与铭牌底对齐（对应页面 align-items: flex-end）；logo 按铭牌区块垂直居中
  const avatarY = MARGIN + PLATE_H - AVATAR_SIZE
  const logoY = MARGIN + (PLATE_H - LOGO_BOX) / 2
  const maiLogoY = MARGIN + (PLATE_H - AVATAR_SIZE) / 2
  const logo2X = BEST30_SHARE_SIZE.width - MARGIN - MAILOGO_BOX_W
  const logo1X = logo2X - LOGO_GAP - LOGO_BOX

  // maitea logo 尺寸不变；maiLogo 用独立更大盒（宽 220 x 高=头像），fit 保持原始比例不挤压，右对齐不越界
  await drawImageBox(ctx, canvas, '/static/maitea_logo.png', logo1X, logoY, LOGO_BOX, LOGO_BOX)
  await drawImageBox(ctx, canvas, '/static/maiLogo.png', logo2X, maiLogoY, MAILOGO_BOX_W, AVATAR_SIZE)

  if (!profile) {
    return
  }
  // 头像（112 正方形，与铭牌可见框体等高并底对齐）
  await drawImageBox(ctx, canvas, profile.avatarSrc, MARGIN, avatarY, AVATAR_SIZE, AVATAR_SIZE, {
    cover: true,
  })
  // 铭牌：396 x 134 保持比例裁切（图片顶部 16/96 透明带，可见框体 ≈112 与头像等高）；加载失败回退浅色底
  const px = MARGIN + AVATAR_SIZE + 16
  const py = MARGIN
  let hasPlate = false
  if (profile.nameplateSrc) {
    hasPlate = await drawImageBox(ctx, canvas, profile.nameplateSrc, px, py, PLATE_W, PLATE_H, {
      radius: 16,
      cover: true,
    })
  }
  if (!hasPlate) {
    drawRoundRect(ctx, px, py, PLATE_W, PLATE_H, 16)
    ctx.fillStyle = PLATE_BG
    ctx.fill()
    ctx.strokeStyle = PLATE_BORDER
    ctx.lineWidth = 2
    ctx.stroke()
  }
  const onImage = hasPlate

  // LV（右上角，可见框体内）：距右缘 22px；有图时下移到 top≈30（透明带之下，baseline 取 py+50），
  // 无图（无透明带）时 top≈12（baseline py+32）
  const lvFont = 'bold 26px sans-serif'
  ctx.textAlign = 'right'
  if (onImage) {
    fillTextOutline(ctx, `LV.${profile.level}`, px + PLATE_W - 22, py + 50, lvFont, '#ffffff', 3)
  } else {
    ctx.font = lvFont
    ctx.fillStyle = '#888888'
    ctx.fillText(`LV.${profile.level}`, px + PLATE_W - 22, py + 32)
  }
  ctx.textAlign = 'left'

  // Rating（左下）：白字黑描边 + 分段底色（对应 .rating-*）
  const ratingFont = 'bold 34px sans-serif'
  ctx.font = ratingFont
  const ratingText = profile.ratingText
  const ratingW = ctx.measureText(ratingText).width + 20
  const tone = RATING_COLORS[profile.ratingTier] || '#999999'
  drawRoundRect(ctx, px + 14, py + 48, ratingW, 36, 8)
  ctx.fillStyle = tone
  ctx.fill()
  fillTextOutline(ctx, ratingText, px + 24, py + 74, ratingFont, '#ffffff')

  // 玩家名（左下）：几乎整条铭牌宽
  const nameFont = 'bold 30px sans-serif'
  const name = truncateText(ctx, profile.name, PLATE_W - 28, nameFont)
  if (onImage) {
    fillTextOutline(ctx, name, px + 14, py + 118, nameFont, '#ffffff', 4)
  } else {
    ctx.font = nameFont
    ctx.fillStyle = TEXT_DARK
    ctx.fillText(name, px + 14, py + 118)
  }
}


/** 单张 b30 分数卡片 */
const drawCard = async (
  ctx: any,
  canvas: any,
  item: BestScoreView,
  cx: number,
  cy: number
): Promise<void> => {
  // 卡片白底 + 浅描边（透明网格即 skyblue 露出的间隔）
  drawRoundRect(ctx, cx, cy, CELL_W, CELL_H, 14)
  ctx.fillStyle = '#ffffff'
  ctx.fill()
  ctx.strokeStyle = '#dfe5ee'
  ctx.lineWidth = 2
  ctx.stroke()

  // 封面：左侧 80 x 80 圆角（保持比例裁切）
  await drawImageBox(ctx, canvas, item.coverUrl, cx + 10, cy + 12, 80, 80, {
    radius: 10,
    cover: true,
  })

  // 右列：难度标签（胶囊）+ 定数，宽度不足时自动缩字 / 截断
  const rx = cx + 98
  const rw = CELL_W - 98 - 10 // 80
  const tone = TONE_COLORS[item.difficultyTone] || '#8c8c8c'

  const labelFont = fitFontPx(ctx, item.difficultyLabel, rw - 12, 13, 11)
  const labelW = Math.min(rw, ctx.measureText(item.difficultyLabel).width + 12)
  drawRoundRect(ctx, rx, cy + 12, labelW, 22, 7)
  ctx.fillStyle = tone
  ctx.fill()
  ctx.fillStyle = '#ffffff'
  ctx.font = labelFont
  ctx.fillText(truncateText(ctx, item.difficultyLabel, labelW - 8, labelFont), rx + 6, cy + 29)

  fitFontPx(ctx, item.chartLevelText, rw, 14, 11)
  ctx.fillStyle = tone
  ctx.fillText(truncateText(ctx, item.chartLevelText, rw, ctx.font), rx, cy + 54)

  // 曲名：21px 放不下逐档缩小到 18px，仍放不下再省略号
  const titleFont = fitFontPx(ctx, item.songName, CELL_W - 20, 21, 18)
  ctx.fillStyle = TEXT_DARK
  ctx.font = titleFont
  ctx.fillText(truncateText(ctx, item.songName, CELL_W - 20, titleFont), cx + 10, cy + 114)

  // 达成率 + rate
  ctx.font = 'bold 20px sans-serif'
  ctx.fillStyle = TEXT_BLUE
  ctx.fillText(item.achievementText, cx + 10, cy + 138)
  const achW = ctx.measureText(item.achievementText).width
  ctx.font = '16px sans-serif'
  ctx.fillStyle = TEXT_GRAY
  ctx.fillText(`rate ${item.rateText}`, cx + 10 + achW + 12, cy + 138)

  // 评级图标 + 奖章（一行，放卡片底部）
  await drawBadges(ctx, canvas, item, cx + 10, cy + 148)
}

/** 评级图标 + FC/AP 奖章；缺图回退文字评级 / 浅灰菱形占位 */
const BADGE_H = 40
const drawBadges = async (
  ctx: any,
  canvas: any,
  item: BestScoreView,
  x: number,
  y: number
): Promise<void> => {
  const rankW = Math.round((BADGE_H * 88) / 72) // 49
  let bx = x
  if (item.rankIconUrl) {
    await drawImageBox(ctx, canvas, item.rankIconUrl, bx, y, rankW, BADGE_H, { cover: true })
  } else {
    ctx.font = 'bold 18px sans-serif'
    ctx.fillStyle = '#b8860b'
    ctx.fillText(item.rank || '?', bx, y + 26)
  }
  bx += rankW + 8
  if (item.medalUrl) {
    await drawImageBox(ctx, canvas, item.medalUrl, bx, y, rankW, BADGE_H, { cover: true })
  } else {
    // 浅灰正方棱形虚影占位（与页面一致）
    ctx.save()
    ctx.translate(bx + rankW / 2, y + BADGE_H / 2)
    ctx.rotate(Math.PI / 4)
    ctx.fillStyle = 'rgba(211, 219, 229, 0.8)'
    ctx.fillRect(-10, -10, 20, 20)
    ctx.strokeStyle = '#c9d2de'
    ctx.lineWidth = 2
    ctx.strokeRect(-10, -10, 20, 20)
    ctx.restore()
  }
}

/** 6x5 网格：每个格子一张 b30 分数卡片，左到右上到下 */
const drawGrid = async (ctx: any, canvas: any, best: BestScoreView[]): Promise<void> => {
  for (let r = 0; r < ROWS; r++) {
    for (let c = 0; c < COLS; c++) {
      const index = r * COLS + c
      if (index >= best.length) {
        continue
      }
      const item = best[index]
      const cx = TABLE_X + c * (CELL_W + GAP)
      const cy = TABLE_Y + r * (CELL_H + GAP)
      await drawCard(ctx, canvas, item, cx, cy)
    }
  }
}

export interface Best30ShareOptions {
  profile: ProfileHeaderView | null
  best: BestScoreView[]
}

/**
 * 在离屏 canvas 上绘制分享图并导出临时文件路径。
 * @param canvasNode type="2d" 的 canvas 节点（node）
 * @returns 临时文件路径（png）
 */
export const createBest30ShareFile = (
  canvasNode: any,
  options: Best30ShareOptions
): Promise<string> => {
  return new Promise<string>((resolve, reject) => {
    try {
      const winInfo = (wx as any).getWindowInfo
      // 像素密度上限 2：避免高 DPI 屏（3x）把画布撑到 3240x4506，成图过大
      const dpr = Math.max(1, Math.min(2, (winInfo ? winInfo().pixelRatio : 2) || 2))
      const base = BEST30_SHARE_SIZE
      canvasNode.width = base.width * dpr
      canvasNode.height = base.height * dpr
      const ctx = canvasNode.getContext('2d')
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0)

      // 背景：skyblue 纯色
      ctx.clearRect(0, 0, base.width, base.height)
      ctx.fillStyle = SKYBLUE
      ctx.fillRect(0, 0, base.width, base.height)

      const run = async () => {
        await drawHeader(ctx, canvasNode, options.profile)
        await drawGrid(ctx, canvasNode, options.best)
        // 底部署名
        ctx.font = '22px sans-serif'
        ctx.fillStyle = TEXT_GRAY
        ctx.textAlign = 'center'
        ctx.fillText(FOOTER_TEXT, BEST30_SHARE_SIZE.width / 2, FOOTER_Y)
        ctx.textAlign = 'left'
        // 用 JPEG 导出并压缩（照片类内容 PNG 会非常大）；图片不透明，JPEG 无损可接受
        wx.canvasToTempFilePath({
          canvas: canvasNode,
          fileType: 'jpg',
          quality: 0.85,
          width: canvasNode.width,
          height: canvasNode.height,
          success: (res: any) => {
            resolve(res.tempFilePath)
          },
          fail: (err: any) => {
            reject(err)
          },
        })
      }
      run().catch((err) => reject(err))
    } catch (e) {
      reject(e)
    }
  })
}

/**
 * 以“图片”形式分享：优先 wx.showShareImageMenu（发送给朋友/收藏/下载均为图片，
 * 避免被识别为普通文件）；不支持的版本退回保存相册。
 */
export const shareBest30Image = (tempFilePath: string): void => {
  const showMenu = (wx as any).showShareImageMenu
  if (typeof showMenu === 'function') {
    showMenu({
      path: tempFilePath,
      fail: () => {
        // 用户取消菜单等：静默处理，不打断
      },
    })
    return
  }
  wx.saveImageToPhotosAlbum({
    filePath: tempFilePath,
    fail: () => {
      wx.showToast({ title: '导出失败，请重试', icon: 'none' })
    },
  })
}

